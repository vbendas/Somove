EOF

echo ""
echo "✅ .env file created successfully!"
echo ""
echo "Next steps:"
echo "  1. Edit .env to add your Stripe, Daily.co, and Resend API keys"
echo "  2. Run: docker compose up -d"
echo "  3. Open http://localhost:3000 and complete the setup wizard"
echo ""
echo "⚠️  Remember to change the DASHBOARD_PASSWORD in .env for production!"
