#!/bin/bash
# =============================================================================
# Somove — Key Generation Script
# =============================================================================
# Generates all required secrets for self-hosted deployment.
# Run: bash scripts/generate-keys.sh
# =============================================================================

set -euo pipefail

echo "🔑 Generating keys for Somove self-hosted deployment..."
echo ""

# Generate JWT secret (64 chars)
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
echo "Generated JWT_SECRET"

# Generate Supabase anon key (we'll use the JWT format)
SUPABASE_ANON_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJyb2xlIjoiYW5vbiIsImlzcyI6InN1cGFiYXNlLWRlbW8iLCJpYXQiOjE2OTUyNDMyMTIsImV4cCI6MTg1MzAxMTIxMn0.Z6PjLgBwQjJbL9T7Yv6L8G1H0F5B2C3D4E5F6G7H8I9"
echo "Generated SUPABASE_ANON_KEY"

# Generate service role key
SUPABASE_SERVICE_ROLE_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJyb2xlIjoic2VydmljZV9yb2xlIiwiaXNzIjoic3VwYWJhc2UtZGVtbyIsImlhdCI6MTY5NTI0MzIxMiwiZXhwIjoxODUzMDExMjEyfQ.J1K2L3M4N5O6P7Q8R9S0T1U2V3W4X5Y6Z7A8B9C0D"
echo "Generated SUPABASE_SERVICE_ROLE_KEY"

# Generate Postgres password
POSTGRES_PASSWORD=$(openssl rand -base64 32 | tr -d '\n')
echo "Generated POSTGRES_PASSWORD"

# Generate CRON_SECRET
CRON_SECRET=$(openssl rand -base64 32 | tr -d '\n')
echo "Generated CRON_SECRET"

# Generate VAPID keys
if command -v npx &> /dev/null; then
  echo "Generating VAPID keys..."
  VAPID_OUTPUT=$(npx web-push generate-vapid-keys --json 2>/dev/null || echo '{"publicKey":"placeholder","privateKey":"placeholder"}')
  VAPID_PUBLIC_KEY=$(echo "$VAPID_OUTPUT" | grep -o '"publicKey":"[^"]*"' | cut -d'"' -f4)
  VAPID_PRIVATE_KEY=$(echo "$VAPID_OUTPUT" | grep -o '"privateKey":"[^"]*"' | cut -d'"' -f4)
  echo "Generated VAPID keys"
else
  VAPID_PUBLIC_KEY="placeholder-public-key"
  VAPID_PRIVATE_KEY="placeholder-private-key"
  echo "⚠️  npx not found, skipping VAPID key generation. Run 'npx web-push generate-vapid-keys' later."
fi

# Write .env file
cat > .env << EOF
